import dev.rustmodforge.core.compat.HorizonCompat
import dev.rustmodforge.core.geo.AnimationSampler
import dev.rustmodforge.core.geo.RigAnimation
import dev.rustmodforge.core.geo.RigModel
import dev.rustmodforge.core.model.EntityInfo
import dev.rustmodforge.core.model.GoalSelectorKind
import dev.rustmodforge.core.model.TraitKind
import dev.rustmodforge.core.report.FeatureResult
import dev.rustmodforge.core.report.FeatureStatus
import java.util.Locale

/**
 * Writes a native trait mod for upstream (desktop) Horizon: a `horizon-mixin.toml` bundle with an
 * `[api]` crate implementing `horizon_client::mod_api::Hooks`. It uses only APIs read in
 * Horizon's source at [HorizonCompat.UPSTREAM_REVISION]: `register_goals` with
 * `horizon_client::mobs::goals` (vanilla goals and custom `Goal` impls) and `mob_submit`
 * drawing the mod's own model with `Host::draw_cube` under the frame's pose stack.
 *
 * Horizon Android cannot load this (`.hnmod` is unsupported there); it is the desktop route.
 */
class NativeModGenerator(private val modId: String, private val version: String, private val out: OutputTree) {
    val features = ArrayList<FeatureResult>()
    val warnings = ArrayList<String>()
    private val crate = "mod-${modId.replace('_', '-')}"

    companion object {
        /** The only part of lib.rs an AI repair may replace. */
        const val REGION_START = "// <rmf:goals>"
        const val REGION_END = "// </rmf:goals>"
        /** The API facts a repair prompt may rely on (from Horizon's source at the pinned revision). */
        val API_NOTES = """
            horizon_client::mobs::goals::Goal trait: fn flags(&self) -> u8; fn can_use(&mut self, m: &mut Mob, cx: &mut Cx) -> bool;
            fn can_continue(&mut self, m: &mut Mob, cx: &mut Cx) -> bool; fn start/stop/tick(&mut self, m: &mut Mob, cx: &mut Cx); fn box_clone(&self) -> Box<dyn Goal>.
            goals::{MOVE, LOOK, JUMP, TARGET}: u8 flags. Mob fields: position (x, y, z f64), removed: bool, invisible: bool, ai.target: Option<Who>,
            ai.nav.is_done(). Mob methods: nav_move_to(cx.w, [f64; 3], speed) -> bool, look_at([f64; 3]).
            Cx fields: w: &MobWorld (nearest_player: Option<Vec3>, player: Option<PlayerView{eye:[f64;3], look:[f64;3], alive, position}>, day_time: i64, daylight: bool).
        """.trimIndent()
    }

    class EntityPlan(val entity: EntityInfo, val rig: RigModel?, val animations: List<RigAnimation>, val hasTexture: Boolean)

    fun generate(plans: List<EntityPlan>) {
        val bundle = "mixins/$modId"
        out.putText("$bundle/horizon-mixin.toml", """
            |# $modId: a native trait mod generated by RustMod Forge (docs/native-mods.md, "Trait mods").
            |# Desktop Horizon only. Build: horizon-launcher native-build <folder> --trust-native-code
            |[mod]
            |id = "$modId"
            |version = "$version"
            |
            |[compatibility]
            |horizon_revision = "${HorizonCompat.UPSTREAM_REVISION}"
            |
            |[api]
            |path = "api"
            |""".trimMargin())
        out.putText("$bundle/api/Cargo.toml", """
            |[package]
            |name = "$crate"
            |version = "$version"
            |edition = "2024"
            |
            |[dependencies]
            |# The launcher points this at the Horizon source it builds the game from.
            |horizon-client = { git = "https://github.com/horizon-rust/horizon", rev = "${HorizonCompat.UPSTREAM_REVISION}" }
            |""".trimMargin())
        out.putText("$bundle/api/src/lib.rs", lib(plans))
        out.putText("horizon-native.json", """
            |{
            |  "schema": 1,
            |  "id": "$modId",
            |  "version": "$version",
            |  "game": "${HorizonCompat.MINECRAFT}",
            |  "horizon": "${HorizonCompat.UPSTREAM_REVISION}",
            |  "mixins": "${HorizonCompat.MIXINS_REVISION}"
            |}
            |""".trimMargin())
    }

    private fun f(d: Double): String {
        val s = String.format(Locale.ROOT, "%.4f", d).trimEnd('0')
        return if (s.endsWith(".")) s + "0" else s
    }
    private fun f3(v: List<Double>) = "[${v.joinToString(", ") { f(it) }}]"
    private fun ident(s: String) = s.uppercase().replace(Regex("[^A-Z0-9]"), "_").let { if (it.first().isDigit()) "M_$it" else it }

    private fun lib(plans: List<EntityPlan>): String = buildString {
        appendLine("//! Generated by RustMod Forge for upstream Horizon ${HorizonCompat.UPSTREAM_REVISION.take(12)}.")
        appendLine("//! Reconstructed from the Java mod's bytecode; see the conversion report for what each part")
        appendLine("//! reproduces and what it does not. Review before building: native mods are not sandboxed.")
        appendLine("#![allow(clippy::all, dead_code, unused_variables, unused_imports)]")
        appendLine("use horizon_client::mob" + "s::{Mob, goals::{self, Cx, Goal}};")
        appendLine("use horizon_client::mod_api::{CubeFace, Flow, Hooks, Host, MobSubmitEvent, RegisterGoalsEvent};")
        appendLine()
        appendLine("pub fn hooks() -> Box<dyn Hooks> {")
        appendLine("    Box::new(Mod)")
        appendLine("}")
        appendLine()
        appendLine("struct Mod;")
        appendLine()
        appendLine(REGION_START)
        appendLine(goalTypes())
        appendLine(REGION_END)
        val drawn = plans.filter { it.rig != null && it.hasTexture }
        for (p in drawn) appendLine(modelTables(p))
        appendLine(drawSupport())
        appendLine("impl Hooks for Mod {")
        appendLine("    /// Mob.registerGoals for the mod's entity types.")
        appendLine("    fn register_goals(&self, event: &mut RegisterGoalsEvent<'_>) {")
        appendLine("        let kind = event.mob.kind.id.to_string();")
        for (p in plans) append(registerGoals(p))
        appendLine("    }")
        if (drawn.isNotEmpty()) {
            appendLine()
            appendLine("    /// RenderLivingEvent.Pre: draws the mod's own model and hides the template's.")
            appendLine("    fn mob_submit(&self, host: &dyn Host, event: &mut MobSubmitEvent<'_>) -> Flow {")
            for (p in drawn) {
                val n = ident(p.entity.id.substringAfter(':'))
                appendLine("        if event.mob.kind == \"${p.entity.id}\" {")
                appendLine("            draw_model(host, event, &${n}_BONES, &${n}_CLIPS, \"$modId:item/rig/${p.entity.id.substringAfter(':')}\");")
                appendLine("            return Flow::Cancel;")
                appendLine("        }")
            }
            appendLine("        Flow::Continue")
            appendLine("    }")
        }
        appendLine("}")
    }

    private fun registerGoals(p: EntityPlan): String = buildString {
        val e = p.entity
        val traits = e.traits.map { it.kind }.toSet()
        fun param(k: TraitKind, key: String) = e.traits.firstOrNull { it.kind == k }?.params?.get(key)?.toDoubleOrNull()
        appendLine("        if kind == \"${e.id}\" {")
        appendLine("            let ai = &mut event.mob.ai;")
        appendLine("            ai.goals.clear();")
        appendLine("            ai.targets.clear();")
        val mapped = ArrayList<String>(); val skipped = ArrayList<String>()
        if (TraitKind.VANISH_WHEN_APPROACHED in traits) {
            appendLine("            ai.goals.add(0, VanishWhenNear { distance: ${f(param(TraitKind.VANISH_WHEN_APPROACHED, "distance") ?: 8.0)} });")
            mapped += "VanishWhenNear"
        }
        if (TraitKind.FREEZE_WHEN_LOOKED_AT in traits) { appendLine("            ai.goals.add(0, FreezeWhenWatched);"); mapped += "FreezeWhenWatched" }
        if (TraitKind.WATCH_FROM_DISTANCE in traits) { appendLine("            ai.goals.add(1, WatchPlayer);"); mapped += "WatchPlayer" }
        for (g in e.goals) {
            val a = g.args.mapNotNull { it.toDoubleOrNull() }
            val line = when (g.goal) {
                "FloatGoal" -> "goals::Float"
                "WaterAvoidingRandomStrollGoal", "RandomStrollGoal" -> "goals::Stroll::new(${f(a.firstOrNull() ?: 1.0)})"
                "LookAtPlayerGoal" -> "goals::LookAtPlayer::new(${f(a.lastOrNull() ?: 8.0)})"
                "MeleeAttackGoal" -> "goals::MeleeAttack::new(${f(a.getOrNull(0) ?: 1.0)}, ${(a.getOrNull(1) ?: 0.0) != 0.0})"
                "LeapAtTargetGoal" -> "goals::LeapAtTarget::new(${f(a.firstOrNull() ?: 0.4)})"
                "PanicGoal" -> "goals::Panic::new(${f(a.firstOrNull() ?: 1.25)})"
                "NearestAttackableTargetGoal" -> if ("Player" in g.targets) "goals::NearestTarget::new(goals::Prey::Player, ${(a.lastOrNull() ?: 1.0) != 0.0})" else null
                "HurtByTargetGoal" -> "goals::HurtByTarget::new()"
                else -> if (g.custom) customGoal(g.goal, traits, e) else null
            }
            if (line == null) { skipped += g.goal.substringAfterLast('.'); continue }
            val selector = if (g.selector == GoalSelectorKind.TARGET) "targets" else "goals"
            appendLine("            ai.$selector.add(${g.priority}, $line);")
            mapped += g.goal.substringAfterLast('.')
        }
        appendLine("            return;")
        appendLine("        }")
        features += FeatureResult("Behaviour", "Goals of ${e.id}", if (skipped.isEmpty()) FeatureStatus.IMPLEMENTED else FeatureStatus.PARTIAL,
            "Rust register_goals: ${mapped.joinToString()}",
            if (skipped.isEmpty()) "" else "no Horizon equivalent constructed for: ${skipped.joinToString()} (RandomLookAround has no public constructor; custom goals are rebuilt only from recognised behaviours)",
            target = "desktop")
    }

    /** A custom Java goal becomes the Rust goal of the behaviour it was recognised as. */
    private fun customGoal(cls: String, traits: Set<TraitKind>, e: EntityInfo): String? {
        val evidence = e.traits.filter { t -> t.evidence.any { it.startsWith(cls.substringAfterLast('.')) } }.map { it.kind }
        return when {
            TraitKind.STALK_PLAYER in evidence -> "Stalk { keep: ${f(e.traits.first { it.kind == TraitKind.STALK_PLAYER }.params["keep_distance"]?.toDoubleOrNull() ?: 20.0)}, speed: 1.0 }"
            else -> null
        }
    }

    private fun goalTypes() = """
        |/// Removes the mob when a player comes within `distance` blocks and it has no target.
        |#[derive(Clone, Debug)]
        |struct VanishWhenNear { distance: f64 }
        |impl Goal for VanishWhenNear {
        |    fn flags(&self) -> u8 { goals::MOVE | goals::LOOK }
        |    fn can_use(&mut self, m: &mut Mob, cx: &mut Cx) -> bool {
        |        if m.ai.target.is_some() { return false; }
        |        let Some(p) = cx.w.nearest_player else { return false };
        |        let (dx, dy, dz) = (m.position.x - p.x, m.position.y - p.y, m.position.z - p.z);
        |        dx * dx + dy * dy + dz * dz < self.distance * self.distance
        |    }
        |    fn start(&mut self, m: &mut Mob, _cx: &mut Cx) { m.removed = true; }
        |    fn box_clone(&self) -> Box<dyn Goal> { Box::new(self.clone()) }
        |}
        |
        |/// Follows the nearest player, never closer than `keep` blocks, looking at them.
        |#[derive(Clone, Debug)]
        |struct Stalk { keep: f64, speed: f64 }
        |impl Goal for Stalk {
        |    fn flags(&self) -> u8 { goals::MOVE | goals::LOOK }
        |    fn can_use(&mut self, m: &mut Mob, cx: &mut Cx) -> bool {
        |        let Some(p) = cx.w.nearest_player else { return false };
        |        let (dx, dz) = (m.position.x - p.x, m.position.z - p.z);
        |        dx * dx + dz * dz > self.keep * self.keep
        |    }
        |    fn tick(&mut self, m: &mut Mob, cx: &mut Cx) {
        |        let Some(p) = cx.w.nearest_player else { return };
        |        m.look_at([p.x, p.y + 1.6, p.z]);
        |        m.nav_move_to(cx.w, [p.x, p.y, p.z], self.speed);
        |    }
        |    fn box_clone(&self) -> Box<dyn Goal> { Box::new(self.clone()) }
        |}
        |
        |/// Holds the movement and look flags while a player looks straight at the mob, so no
        |/// lower-priority goal moves it.
        |#[derive(Clone, Debug)]
        |struct FreezeWhenWatched;
        |impl Goal for FreezeWhenWatched {
        |    fn flags(&self) -> u8 { goals::MOVE | goals::LOOK | goals::JUMP }
        |    fn can_use(&mut self, m: &mut Mob, cx: &mut Cx) -> bool {
        |        let Some(p) = &cx.w.player else { return false };
        |        if !p.alive { return false; }
        |        let to = [m.position.x - p.eye[0], m.position.y + 1.6 - p.eye[1], m.position.z - p.eye[2]];
        |        let len = (to[0] * to[0] + to[1] * to[1] + to[2] * to[2]).sqrt();
        |        len > 0.0 && len < 48.0 && (to[0] * p.look[0] + to[1] * p.look[1] + to[2] * p.look[2]) / len > 0.95
        |    }
        |    fn box_clone(&self) -> Box<dyn Goal> { Box::new(self.clone()) }
        |}
        |
        |/// Stands and turns to watch the nearest player.
        |#[derive(Clone, Debug)]
        |struct WatchPlayer;
        |impl Goal for WatchPlayer {
        |    fn flags(&self) -> u8 { goals::MOVE | goals::LOOK }
        |    fn can_use(&mut self, _m: &mut Mob, cx: &mut Cx) -> bool { cx.w.nearest_player.is_some() }
        |    fn tick(&mut self, m: &mut Mob, cx: &mut Cx) {
        |        if let Some(p) = cx.w.nearest_player { m.look_at([p.x, p.y + 1.6, p.z]); }
        |    }
        |    fn box_clone(&self) -> Box<dyn Goal> { Box::new(self.clone()) }
        |}
        |""".trimMargin()

    /** Bone hierarchy, cubes with UVs, and animation clips sampled at 20 Hz, as static tables. */
    private fun modelTables(p: EntityPlan): String = buildString {
        val rig = p.rig!!
        val n = ident(p.entity.id.substringAfter(':'))
        val builder = RigBuilder(rig)
        val index = rig.bones.withIndex().associate { it.value.name to it.index }
        appendLine("static ${n}_BONES: [Bone; ${rig.bones.size}] = [")
        for (b in rig.bones) {
            val cubes = b.cubes.map { c ->
                val model = builder.boneModel(b.copy(cubes = listOf(c)), "")
                @Suppress("UNCHECKED_CAST") val el = (model["elements"] as List<Map<String, Any?>>).first()
                @Suppress("UNCHECKED_CAST") val faces = el["faces"] as Map<String, Map<String, Any?>>
                val k = builder.boneScale.getValue(b.name)
                // Faces in Direction::ALL order: down, up, north, south, west, east.
                val uvs = listOf("down", "up", "north", "south", "west", "east").joinToString(", ") { d ->
                    @Suppress("UNCHECKED_CAST") val uv = faces[d]?.get("uv") as? List<Double>
                    if (uv == null) "None" else "Some([${uv.joinToString(", ") { f(it) }}])"
                }
                val from = (0..2).map { c.origin[it] - c.inflate }
                val to = (0..2).map { c.origin[it] + c.size[it] + c.inflate }
                val rot = c.rotation ?: listOf(0.0, 0.0, 0.0)
                val piv = c.pivot ?: b.pivot
                "Cube { from: ${f3(from)}, to: ${f3(to)}, pivot: ${f3(piv)}, rotation: ${f3(rot)}, uv: [$uvs] }"
            }
            appendLine("    Bone { parent: ${b.parent?.let { index[it] }?.let { "Some($it)" } ?: "None"}, pivot: ${f3(b.pivot)}, rotation: ${f3(b.rotation)}, cubes: &[${cubes.joinToString(", ")}] },")
        }
        appendLine("];")
        val clips = listOf("idle", "walk", "run").mapNotNull { state -> p.animations.firstOrNull { it.name.substringAfterLast('.').lowercase().contains(state) }?.let { state to it } }
        appendLine("static ${n}_CLIPS: [Clip; ${clips.size}] = [")
        for ((state, a) in clips) {
            val sampler = AnimationSampler(a)
            val frames = (Math.ceil(a.length.coerceIn(0.05, 10.0) * 20).toInt()).coerceAtLeast(1)
            val poses = (0 until frames).joinToString(",\n        ") { fr ->
                "&[" + rig.bones.joinToString(", ") { b ->
                    val pose = sampler.pose(b.name, fr / 20.0)
                    "Pose { rotation: ${f3(pose.rotation.toList())}, position: ${f3(pose.position.toList())}, scale: ${f3(pose.scale.toList())} }"
                } + "]"
            }
            appendLine("    Clip { state: \"$state\", looping: ${a.loop != dev.rustmodforge.core.geo.LoopMode.ONCE}, frames: &[\n        $poses\n    ] },")
        }
        appendLine("];")
        features += FeatureResult("Model and animation", "Model of ${p.entity.id}", FeatureStatus.PARTIAL,
            "Rust mob_submit: ${rig.bones.size} bones drawn with Host::draw_cube, template model hidden",
            "cube rotations use the full angle; ${clips.size} clips (${clips.joinToString { it.first }}) chosen by walk speed; attack clips have no client-side signal",
            target = "desktop")
    }

    private fun drawSupport() = """
        |struct Cube { from: [f32; 3], to: [f32; 3], pivot: [f32; 3], rotation: [f32; 3], uv: [Option<[f32; 4]>; 6] }
        |struct Bone { parent: Option<usize>, pivot: [f32; 3], rotation: [f32; 3], cubes: &'static [Cube] }
        |#[derive(Clone, Copy)]
        |struct Pose { rotation: [f32; 3], position: [f32; 3], scale: [f32; 3] }
        |struct Clip { state: &'static str, looping: bool, frames: &'static [&'static [Pose]] }
        |
        |fn pick<'a>(clips: &'a [Clip], walk_speed: f32) -> Option<&'a Clip> {
        |    let want = if walk_speed > 0.6 { "run" } else if walk_speed > 0.05 { "walk" } else { "idle" };
        |    clips.iter().find(|c| c.state == want)
        |        .or_else(|| clips.iter().find(|c| c.state == "walk" && want == "run"))
        |        .or_else(|| clips.iter().find(|c| c.state == "idle"))
        |}
        |
        |fn pose_at(clip: Option<&Clip>, bone: usize, age: f32) -> Pose {
        |    let rest = Pose { rotation: [0.0; 3], position: [0.0; 3], scale: [1.0; 3] };
        |    let Some(c) = clip else { return rest };
        |    let n = c.frames.len();
        |    if n == 0 { return rest; }
        |    let t = if c.looping { age % n as f32 } else { age.min((n - 1) as f32) };
        |    let (i, f) = (t.floor() as usize % n, t.fract());
        |    let j = if c.looping { (i + 1) % n } else { (i + 1).min(n - 1) };
        |    let (a, b) = (c.frames[i][bone], c.frames[j][bone]);
        |    let mix = |x: [f32; 3], y: [f32; 3]| [x[0] + (y[0] - x[0]) * f, x[1] + (y[1] - x[1]) * f, x[2] + (y[2] - x[2]) * f];
        |    Pose { rotation: mix(a.rotation, b.rotation), position: mix(a.position, b.position), scale: mix(a.scale, b.scale) }
        |}
        |
        |/// The bone's transform onto the pose stack, as Bedrock/GeckoLib apply it (pixels, Z·Y·X about the pivot).
        |fn apply_bone(draw: &mut horizon_client::mod_api::BlockEntityDraw, bones: &[Bone], i: usize, clip: Option<&Clip>, age: f32) {
        |    if let Some(p) = bones[i].parent { apply_bone(draw, bones, p, clip, age); }
        |    let b = &bones[i];
        |    let pose = pose_at(clip, i, age);
        |    let px = [b.pivot[0] / 16.0, b.pivot[1] / 16.0, b.pivot[2] / 16.0];
        |    draw.translate([pose.position[0] / 16.0, pose.position[1] / 16.0, pose.position[2] / 16.0]);
        |    draw.rotate_about([0.0, 0.0, 1.0], b.rotation[2] + pose.rotation[2], px);
        |    draw.rotate_about([0.0, 1.0, 0.0], b.rotation[1] + pose.rotation[1], px);
        |    draw.rotate_about([1.0, 0.0, 0.0], b.rotation[0] + pose.rotation[0], px);
        |    draw.translate(px);
        |    draw.scale(pose.scale);
        |    draw.translate([-px[0], -px[1], -px[2]]);
        |}
        |
        |fn draw_model(host: &dyn Host, event: &mut MobSubmitEvent<'_>, bones: &[Bone], clips: &[Clip], sprite: &str) {
        |    let clip = pick(clips, event.mob.walk_speed);
        |    let age = event.mob.age;
        |    let draw = &mut *event.draw;
        |    // The frame faces +z; Bedrock models face -z.
        |    draw.push();
        |    draw.rotate_about([0.0, 1.0, 0.0], 180.0, [0.0, 0.0, 0.0]);
        |    for (i, bone) in bones.iter().enumerate() {
        |        if bone.cubes.is_empty() { continue; }
        |        draw.push();
        |        apply_bone(draw, bones, i, clip, age);
        |        for c in bone.cubes {
        |            draw.push();
        |            let cp = [c.pivot[0] / 16.0, c.pivot[1] / 16.0, c.pivot[2] / 16.0];
        |            draw.rotate_about([0.0, 0.0, 1.0], c.rotation[2], cp);
        |            draw.rotate_about([0.0, 1.0, 0.0], c.rotation[1], cp);
        |            draw.rotate_about([1.0, 0.0, 0.0], c.rotation[0], cp);
        |            let faces = c.uv.map(|uv| uv.map(|uv| CubeFace { sprite, uv: Some(uv) }));
        |            let from = [c.from[0] / 16.0, c.from[1] / 16.0, c.from[2] / 16.0];
        |            let to = [c.to[0] / 16.0, c.to[1] / 16.0, c.to[2] / 16.0];
        |            host.draw_cube(draw, from, to, faces, 0xFF_FF_FF);
        |            draw.pop();
        |        }
        |        draw.pop();
        |    }
        |    draw.pop();
        |}
        |""".trimMargin()
}
