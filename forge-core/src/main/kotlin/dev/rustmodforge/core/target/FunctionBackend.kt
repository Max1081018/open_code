package dev.rustmodforge.core.target

import dev.rustmodforge.core.archive.SafeArchive
import dev.rustmodforge.core.geo.AnimationSampler
import dev.rustmodforge.core.geo.LoopMode
import dev.rustmodforge.core.geo.RigAnimation
import dev.rustmodforge.core.geo.RigModel
import dev.rustmodforge.core.model.BehaviourTrait
import dev.rustmodforge.core.model.EntityInfo
import dev.rustmodforge.core.model.TraitKind
import dev.rustmodforge.core.report.FeatureResult
import dev.rustmodforge.core.report.FeatureStatus
import dev.rustmodforge.core.util.JsonTree
import kotlin.math.ceil
import kotlin.math.roundToInt

/**
 * The Android route for entity appearance and behaviour. Horizon Android has no entity model or
 * AI API for mods, but it runs data pack functions (`#minecraft:tick`), and vanilla's display
 * entities and commands are enough to rebuild a creature:
 *
 *  - the mob itself is the content entity type (a zombie- or trader-class mob for movement,
 *    pathfinding, collision, saving), made invisible and silent;
 *  - its model is a rig of `item_display` entities, one per bone, each showing an item model
 *    generated from that bone's cubes, following the mob every tick;
 *  - animations are sampled into frames that set each bone's display transformation with
 *    interpolation, chosen by state (idle/walk/run/attack) as a GeckoLib controller would;
 *  - behaviours recognised in the bytecode (stalking, watching, vanishing, freezing when looked
 *    at, effects, sounds, particles) become a per-tick state machine.
 *
 * None of this has been run on a device by RustMod Forge; the report says so.
 */
class FunctionBackend(
    private val modId: String,
    private val out: OutputTree,
    private val archive: SafeArchive,
    private val frameStep: Int = 2,
    private val maxClipSeconds: Double = 10.0,
) {
    val features = ArrayList<FeatureResult>()
    val warnings = ArrayList<String>()
    private val tickLines = ArrayList<String>()
    private val loadLines = ArrayList<String>()
    private val ns = modId
    private val obj = "$ns.v"           // per-entity values: uid, state, frame...
    private val tmp = "$ns.t"

    class EntityPlan(
        val entity: EntityInfo,
        val rig: RigModel?,
        val animations: List<RigAnimation>,
        val texturePath: String?,
        val glowTexturePath: String?,
        /** The vanilla mob that carries it (Horizon Android declares no living mob types). */
        val body: String = "minecraft:zombie",
        /** Allowed `/attribute` ids on that body. */
        val bodyAttributes: Set<String> = emptySet(),
    )

    fun generate(plans: List<EntityPlan>) {
        loadLines += "scoreboard objectives add $obj.uid dummy"
        loadLines += "scoreboard objectives add $obj.anim dummy"
        loadLines += "scoreboard objectives add $obj.frame dummy"
        loadLines += "scoreboard objectives add $obj.atk dummy"
        loadLines += "scoreboard objectives add $obj.px dummy"
        loadLines += "scoreboard objectives add $obj.pz dummy"
        loadLines += "scoreboard objectives add $tmp dummy"
        loadLines += "scoreboard players set #20 $tmp 20"
        out.putJson("assets/$ns/items/rig/empty.json", JsonTree.of("model" to JsonTree.of("type" to "minecraft:empty")))
        out.putJson("data/$ns/predicate/chance/ambient.json", JsonTree.of("condition" to "minecraft:random_chance", "chance" to 0.0125))
        out.putJson("data/$ns/predicate/chance/particles.json", JsonTree.of("condition" to "minecraft:random_chance", "chance" to 0.25))
        tickLines += "scoreboard players add #timer $tmp 1"
        tickLines += "scoreboard players operation #slow $tmp = #timer $tmp"
        tickLines += "scoreboard players operation #slow $tmp %= #20 $tmp"
        tickLines += "execute store result score #time $tmp run time query daytime"
        tickLines += "scoreboard players set #night $tmp 0"
        tickLines += "execute if score #time $tmp matches 13000..23000 run scoreboard players set #night $tmp 1"
        for (p in plans) entity(p)
        // Rig parts whose mob is gone (killed, unloaded without its rig) are removed once a second.
        tickLines += "execute if score #slow $tmp matches 0 run kill @e[type=minecraft:item_display,tag=$ns.rig,tag=!$ns.alive]"
        tickLines += "execute if score #slow $tmp matches 0 run tag @e[type=minecraft:item_display,tag=$ns.rig] remove $ns.alive"
        out.putText("data/$ns/function/load.mcfunction", header("load") + loadLines.joinToString("\n") + "\n")
        out.putText("data/$ns/function/tick.mcfunction", header("tick") + tickLines.joinToString("\n") + "\n")
        mergeTag("data/minecraft/tags/function/load.json", "$ns:load")
        mergeTag("data/minecraft/tags/function/tick.json", "$ns:tick")
    }

    private fun header(what: String) = "# $what — generated by RustMod Forge. Runs at function permission level 2.\n"

    private fun mergeTag(path: String, value: String) {
        val tag = if (out.exists(path)) JsonTree.obj(JsonTree.parse(out.readText(path))) ?: LinkedHashMap() else LinkedHashMap()
        val values = JsonTree.list(tag["values"]) ?: ArrayList<Any?>().also { tag["values"] = it }
        if (value !in values) values += value
        out.putJson(path, tag)
    }

    private fun fn(path: String, lines: List<String>) = out.putText("data/$ns/function/$path.mcfunction", lines.joinToString("\n") + "\n")

    private fun entity(p: EntityPlan) {
        val e = p.entity
        val name = e.id.substringAfter(':')
        val type = e.id
        val base = "e/$name"
        val traits = e.traits.groupBy { it.kind }
        val tag = ContentModGenerator.creatureTag(ns, name)
        val sel = "type=${p.body},tag=$tag"

        // ---------- rig assets ----------
        val rig = p.rig?.let { RigBuilder(it) }
        val boneTag = { bone: String -> "$ns.b.$name.$bone" }
        val spawnRig = ArrayList<String>()
        if (rig != null && p.texturePath != null) {
            val tex = "$ns:item/rig/$name"
            out.copyFrom(archive, p.texturePath, "assets/$ns/textures/item/rig/$name.png")
            p.glowTexturePath?.let { out.copyFrom(archive, it, "assets/$ns/textures/item/rig/${name}_glow.png") }
            val rest = rig.pose(null, 0.0)
            for (b in rig.drawnBones) {
                out.putJson("assets/$ns/models/item/rig/$name/${b.name}.json", rig.boneModel(b, tex))
                out.putJson("assets/$ns/items/rig/$name/${b.name}.json",
                    JsonTree.of("model" to JsonTree.of("type" to "minecraft:model", "model" to "$ns:item/rig/$name/${b.name}")))
                val t = rest.getValue(b.name)
                spawnRig += summon(b.name, "$ns:rig/$name/${b.name}", boneTag(b.name), t.snbt(), glow = false)
                if (p.glowTexturePath != null) {
                    out.putJson("assets/$ns/models/item/rig/$name/${b.name}_glow.json", rig.boneModel(b, "$ns:item/rig/${name}_glow", 0.05))
                    out.putJson("assets/$ns/items/rig/$name/${b.name}_glow.json",
                        JsonTree.of("model" to JsonTree.of("type" to "minecraft:model", "model" to "$ns:item/rig/$name/${b.name}_glow")))
                    spawnRig += summon("${b.name}_glow", "$ns:rig/$name/${b.name}_glow", boneTag(b.name), t.snbt(), glow = true)
                }
            }
            rig.approximations.distinct().forEach { warnings += "$type: $it" }
            features += FeatureResult("Model and animation", "Model of $type", FeatureStatus.PARTIAL,
                "display-entity rig: ${rig.drawnBones.size} bone models from ${p.rig.source.substringBefore(':')} geometry (${p.rig.cubeCount} cubes)",
                buildList {
                    add("drawn by item_display entities, not as one mob model: no hurt tint, shadow is the template's")
                    if (rig.approximations.isNotEmpty()) add("${rig.approximations.size} cube rotations approximated")
                    add("orientation and handedness not yet checked on a device")
                }.joinToString("; "))
            if (p.glowTexturePath != null) features += FeatureResult("Model and animation", "Emissive layer of $type", FeatureStatus.PARTIAL,
                "second rig at full brightness with the glowmask texture", "drawn as a slightly inflated copy, not a shader pass")
        } else {
            features += FeatureResult("Model and animation", "Model of $type", FeatureStatus.UNSUPPORTED,
                reason = if (p.rig == null) "no geometry was found (GeckoLib .geo.json or a createBodyLayer model): it keeps the template's look"
                else "no texture was found for it: it keeps the template's look")
        }

        // ---------- init (once per mob) ----------
        val init = ArrayList<String>()
        init += "# The mob carries movement, collision and saving; the rig draws it."
        init += "scoreboard players add #next $tmp 1"
        init += "scoreboard players operation @s $obj.uid = #next $tmp"
        init += "tag @s add $ns.ready"
        val nbt = mutableListOf("Silent:1b", "CanPickUpLoot:0b", "IsBaby:0b", "CanBreakDoors:0b")
        if (TraitKind.PERSISTENT in traits) nbt += "PersistenceRequired:1b"
        val loot = if (out.exists("data/$ns/loot_table/entities/$name.json")) "$ns:entities/$name" else "minecraft:empty"
        nbt += "DeathLootTable:\"$loot\""
        init += "data merge entity @s {${nbt.joinToString(",")}}"
        val attrs = e.attributes.filterKeys { it in p.bodyAttributes }
        for ((a, v) in attrs) init += "attribute @s $a base set ${dev.rustmodforge.core.bytecode.Events.fmt(v)}"
        e.attributes["minecraft:max_health"]?.let { init += "data merge entity @s {Health:${dev.rustmodforge.core.bytecode.Events.fmt(it)}f}" }
        if (attrs.isNotEmpty()) features += FeatureResult("Entities", "Attributes of $type", if (attrs.size == e.attributes.size) FeatureStatus.IMPLEMENTED else FeatureStatus.PARTIAL,
            "/attribute on its first tick: ${attrs.entries.joinToString { "${it.key.removePrefix("minecraft:")}=${dev.rustmodforge.core.bytecode.Events.fmt(it.value)}" }}",
            if (attrs.size == e.attributes.size) "" else "not on a ${p.body}: ${(e.attributes.keys - attrs.keys).joinToString()}")
        if (rig != null && p.texturePath != null) {
            init += "effect give @s minecraft:invisibility infinite 0 true"
            init += "# An invisible head item: keeps the zombie class from burning in daylight, draws nothing."
            init += "item replace entity @s armor.head with minecraft:paper[minecraft:item_model=\"$ns:rig/empty\"]"
            init += spawnRig
            init += "scoreboard players operation @e[type=minecraft:item_display,tag=$ns.new,distance=..2] $obj.uid = @s $obj.uid"
            init += "tag @e[type=minecraft:item_display,tag=$ns.new,distance=..2] remove $ns.new"
        }
        fn("$base/init", init)

        // ---------- animations ----------
        val clips = assignClips(p.animations)
        val animLines = ArrayList<String>()
        if (rig != null && p.texturePath != null && clips.isNotEmpty()) {
            for ((idx, clip) in clips.values.withIndex()) writeClip(rig, clip, name, idx, boneTag)
            animLines += animationSelector(name, clips)
            features += FeatureResult("Model and animation", "Animations of $type (${clips.size} used of ${p.animations.size})", FeatureStatus.PARTIAL,
                "sampled every $frameStep ticks into display transformations: ${clips.entries.joinToString { "${it.key}=${it.value.name.substringAfterLast('.')}" }}",
                buildList {
                    add("between samples the client interpolates linearly")
                    val unused = p.animations.map { it.name } - clips.values.map { it.name }.toSet()
                    if (unused.isNotEmpty()) add("not mapped to a state: ${unused.joinToString { it.substringAfterLast('.') }}")
                    val approx = p.animations.flatMap { it.approximations }.distinct()
                    if (approx.isNotEmpty()) add(approx.joinToString())
                }.joinToString("; "))
        } else if (p.animations.isNotEmpty()) {
            features += FeatureResult("Model and animation", "Animations of $type", FeatureStatus.UNSUPPORTED,
                reason = "there is no rig to animate (see the model row)")
        }

        // ---------- behaviour ----------
        val ai = ArrayList<String>()
        ai += "scoreboard players operation #cur $tmp = @s $obj.uid"
        if (rig != null && p.texturePath != null) {
            ai += "execute as @e[type=minecraft:item_display,tag=$ns.rig,distance=..24] if score @s $obj.uid = #cur $tmp run function $ns:rig/follow"
        }
        ai += behaviour(e, traits, name, base)
        ai += animLines
        fn("$base/tick", ai)
        fn("rig/follow", listOf("tp @s ~ ~ ~ ~ 0", "tag @s add $ns.alive"))

        tickLines += "execute as @e[$sel,tag=!$ns.ready] at @s run function $ns:$base/init"
        tickLines += "execute as @e[$sel] at @s run function $ns:$base/tick"

        // ---------- spawning ----------
        fn("summon/$name", listOf("# /function $ns:summon/$name places one where the command runs.", "summon ${p.body} ~ ~ ~ {Tags:[\"$tag\"]}"))
        val spawn = e.spawn
        if (spawn != null || e.category == "monster") {
            val weight = spawn?.weight ?: 5
            val chance = (weight * 0.0005).coerceIn(0.0005, 0.02)
            out.putJson("data/$ns/predicate/spawn/$name.json", JsonTree.of("condition" to "minecraft:random_chance", "chance" to chance))
            val monster = e.category == "monster"
            val gate = if (monster) "if score #night $tmp matches 1 " else ""
            fn("$base/spawn_near", listOf(
                "# Runs as a player, once a second with the chance in predicate $ns:spawn/$name.",
                "execute ${gate}unless entity @e[$sel,distance=..96] positioned ^ ^ ^-28 positioned over motion_blocking_no_leaves run summon ${p.body} ~ ~ ~ {Tags:[\"$tag\"]}",
            ))
            tickLines += "execute if score #slow $tmp matches 0 as @a[gamemode=!spectator] at @s if predicate $ns:spawn/$name run function $ns:$base/spawn_near"
            features += FeatureResult("Entities", "Spawning of $type", FeatureStatus.PARTIAL,
                "functions: ${if (monster) "at night, " else ""}about ${"%.2f".format(chance * 100)}% a second per player, 28 blocks behind them on the surface, one within 96 blocks",
                "replaces ${spawn?.source?.ifEmpty { null } ?: "the Java spawn rules"}${spawn?.biomes?.takeIf { it.isNotEmpty() }?.let { " (biomes ${it.joinToString()}: not checked by commands)" } ?: ""}; light level is not checked")
        }
    }

    private fun summon(bone: String, itemModel: String, tag: String, transform: String, glow: Boolean): String {
        val brightness = if (glow) ",brightness:{sky:15,block:15}" else ""
        val inner = transform.removePrefix("{").removeSuffix("}")
        return "summon minecraft:item_display ~ ~ ~ {Tags:[\"$ns.rig\",\"$ns.new\",\"$tag\"],item:{id:\"minecraft:paper\",count:1,components:{\"minecraft:item_model\":\"$itemModel\"}}," +
            "item_display:\"none\",teleport_duration:1,view_range:1.5f$brightness,$inner}"
    }

    /** GeckoLib clip names to the states a controller usually switches between. */
    private fun assignClips(animations: List<RigAnimation>): LinkedHashMap<String, RigAnimation> {
        val out = LinkedHashMap<String, RigAnimation>()
        fun find(vararg keys: String) = animations.firstOrNull { a -> keys.any { a.name.substringAfterLast('.').lowercase().contains(it) } }
        find("idle", "stand")?.let { out["idle"] = it }
        find("walk", "move")?.let { out["walk"] = it }
        find("run", "chase", "sprint")?.let { out["run"] = it }
        find("attack", "hit", "swing", "grab")?.let { out["attack"] = it }
        if (out.isEmpty() && animations.isNotEmpty()) out["idle"] = animations.first()
        return out
    }

    private fun ticksOf(a: RigAnimation) = ceil(a.length.coerceIn(0.05, maxClipSeconds) * 20).toInt().coerceAtLeast(frameStep)

    private fun writeClip(rig: RigBuilder, a: RigAnimation, entity: String, index: Int, boneTag: (String) -> String) {
        val sampler = AnimationSampler(a)
        val ticks = ticksOf(a)
        val dispatch = ArrayList<String>()
        var frame = 0
        while (frame < ticks) {
            val t = frame / 20.0
            val pose = rig.pose(a, t, sampler)
            val lines = ArrayList<String>()
            for ((bone, transform) in pose) {
                lines += "execute as @e[type=minecraft:item_display,tag=${boneTag(bone)},distance=..24] if score @s $obj.uid = #cur $tmp run data merge entity @s ${transform.snbt(frameStep)}"
            }
            a.sounds.filter { it.time >= t && it.time < t + frameStep / 20.0 }.forEach {
                val id = if (it.effect.contains(':')) it.effect else "$ns:${it.effect}"
                lines += "playsound $id hostile @a[distance=..32] ~ ~ ~ 1 1"
            }
            fn("e/$entity/anim/$index/f$frame", lines)
            dispatch += "execute if score @s $obj.frame matches $frame run function $ns:e/$entity/anim/$index/f$frame"
            frame += frameStep
        }
        dispatch += "scoreboard players add @s $obj.frame 1"
        dispatch += if (a.loop == LoopMode.LOOP) "execute if score @s $obj.frame matches $ticks.. run scoreboard players set @s $obj.frame 0"
        else "execute if score @s $obj.frame matches $ticks.. run scoreboard players set @s $obj.frame $ticks"
        fn("e/$entity/anim/$index/play", dispatch)
    }

    /** Chooses the clip from movement and attack state, restarting a clip when the state changes. */
    private fun animationSelector(entity: String, clips: Map<String, RigAnimation>): List<String> {
        val idx = clips.keys.withIndex().associate { it.value to it.index }
        val lines = ArrayList<String>()
        lines += "# Speed from the change in position (hundredths of a block per tick, squared)."
        lines += "execute store result score #x $tmp run data get entity @s Pos[0] 100"
        lines += "execute store result score #z $tmp run data get entity @s Pos[2] 100"
        lines += "scoreboard players operation #dx $tmp = #x $tmp"
        lines += "scoreboard players operation #dx $tmp -= @s $obj.px"
        lines += "scoreboard players operation #dz $tmp = #z $tmp"
        lines += "scoreboard players operation #dz $tmp -= @s $obj.pz"
        lines += "scoreboard players operation #dx $tmp *= #dx $tmp"
        lines += "scoreboard players operation #dz $tmp *= #dz $tmp"
        lines += "scoreboard players operation #dx $tmp += #dz $tmp"
        lines += "scoreboard players operation @s $obj.px = #x $tmp"
        lines += "scoreboard players operation @s $obj.pz = #z $tmp"
        val idle = idx["idle"] ?: idx.values.first()
        lines += "scoreboard players set #want $tmp $idle"
        idx["walk"]?.let { lines += "execute if score #dx $tmp matches 4.. run scoreboard players set #want $tmp $it" }
        (idx["run"] ?: idx["walk"])?.let { lines += "execute if score #dx $tmp matches 400.. run scoreboard players set #want $tmp $it" }
        idx["attack"]?.let { lines += "execute if score @s $obj.atk matches 1.. run scoreboard players set #want $tmp $it" }
        lines += "scoreboard players remove @s[scores={$obj.atk=1..}] $obj.atk 1"
        lines += "execute unless score @s $obj.anim = #want $tmp run scoreboard players set @s $obj.frame 0"
        lines += "scoreboard players operation @s $obj.anim = #want $tmp"
        for ((state, i) in idx) lines += "execute if score @s $obj.anim matches $i run function $ns:e/$entity/anim/$i/play # $state"
        return lines.map { it.substringBefore(" # ") }
    }

    private fun soundId(s: String?): String? = when {
        s == null -> null
        s.startsWith("vanilla:") -> "minecraft:" + s.removePrefix("vanilla:").lowercase().split('_').let { parts ->
            if (parts.size >= 2) "entity.${parts.first()}.${parts.drop(1).joinToString("_")}" else parts.first()
        }
        s.startsWith("field:") -> null
        else -> s
    }

    private fun behaviour(e: EntityInfo, traits: Map<TraitKind, List<BehaviourTrait>>, name: String, base: String): List<String> {
        val type = e.id
        val lines = ArrayList<String>()
        fun has(k: TraitKind) = traits.containsKey(k)
        fun param(k: TraitKind, key: String) = traits[k]?.firstNotNullOfOrNull { it.params[key]?.toDoubleOrNull() }
        fun ok(feature: String, route: String, reason: String = "", status: FeatureStatus = FeatureStatus.PARTIAL, k: TraitKind? = null) {
            features += FeatureResult("Behaviour", "$feature ($type)", status, route, reason, k?.let { traits[it]?.flatMap { t -> t.evidence } } ?: emptyList())
        }
        val night = has(TraitKind.NIGHT_ONLY)
        val looked = has(TraitKind.FREEZE_WHEN_LOOKED_AT) || has(TraitKind.VANISH_WHEN_LOOKED_AT)
        if (looked) {
            lines += "# Is a player looking at it? Probe points along each nearby player's view (no wall check)."
            lines += "scoreboard players set #looked $tmp 0"
            lines += "tag @s add $ns.self"
            for ((d, r) in listOf(3 to 1.8, 6 to 2.8, 10 to 4.2, 16 to 6.2, 24 to 8.8, 32 to 11.4, 48 to 16.6)) {
                lines += "execute as @a[distance=..${d + 4},gamemode=!spectator] at @s anchored eyes positioned ^ ^ ^$d if entity @e[tag=$ns.self,distance=..$r] run scoreboard players set #looked $tmp 1"
            }
            lines += "tag @s remove $ns.self"
        }
        val chase = has(TraitKind.CHASE_PLAYER)
        lines += "scoreboard players set #chase $tmp ${if (chase) 1 else 0}"
        if (chase && night) lines += "execute if score #night $tmp matches 0 run scoreboard players set #chase $tmp 0"
        if (chase) ok("Chases and attacks players", "the zombie class's target and melee goals", "uses vanilla zombie melee and pathfinding, not the mod's", k = TraitKind.CHASE_PLAYER)

        // Default: the template AI runs.
        lines += "scoreboard players set #hold $tmp 0"
        if (has(TraitKind.WATCH_FROM_DISTANCE)) {
            lines += "execute if score #chase $tmp matches 0 if entity @p[distance=..64,gamemode=!spectator] run scoreboard players set #hold $tmp 1"
            ok("Watches the player from a distance", "functions: stands still (NoAI) and turns to face the nearest player", "no line-of-sight test", k = TraitKind.WATCH_FROM_DISTANCE)
        }
        if (has(TraitKind.STALK_PLAYER)) {
            val keep = param(TraitKind.STALK_PLAYER, "keep_distance") ?: 20.0
            lines += "execute if score #chase $tmp matches 0 if entity @p[distance=..${keep.roundToInt()},gamemode=!spectator] run scoreboard players set #hold $tmp 1"
            ok("Stalks the player, keeping ${keep.roundToInt()} blocks away", "functions: walks with the template's pathfinding, stops within ${keep.roundToInt()} blocks and faces the player",
                "approaches through the template's navigation toward its target", k = TraitKind.STALK_PLAYER)
        }
        if (has(TraitKind.FREEZE_WHEN_LOOKED_AT)) {
            lines += "execute if score #looked $tmp matches 1 run scoreboard players set #hold $tmp 1"
            ok("Freezes while looked at", "functions: view-direction probes set NoAI while a player looks at it", "the view test has no wall check", k = TraitKind.FREEZE_WHEN_LOOKED_AT)
        }
        lines += "execute if score #hold $tmp matches 1 run data merge entity @s {NoAI:1b}"
        lines += "execute if score #hold $tmp matches 1 facing entity @p[gamemode=!spectator] feet run tp @s ~ ~ ~ ~ 0"
        lines += "execute if score #hold $tmp matches 0 run data merge entity @s {NoAI:0b}"

        val vanishSound = soundId(e.sounds.other.firstOrNull()) ?: soundId(e.sounds.hurt)
        val vanish = ArrayList<String>()
        if (has(TraitKind.VANISH_WHEN_APPROACHED) || has(TraitKind.VANISH_WHEN_LOOKED_AT)) {
            vanishSound?.let { vanish += "playsound $it hostile @a[distance=..32] ~ ~ ~ 1 0.6" }
            vanish += "particle minecraft:smoke ~ ~1 ~ 0.3 0.8 0.3 0.02 40"
            vanish += "scoreboard players operation #cur $tmp = @s $obj.uid"
            vanish += "execute as @e[type=minecraft:item_display,tag=$ns.rig,distance=..24] if score @s $obj.uid = #cur $tmp run kill @s"
            vanish += "tp @s ~ -1000 ~"
            vanish += "kill @s"
            fn("$base/vanish", vanish)
        }
        if (has(TraitKind.VANISH_WHEN_APPROACHED)) {
            val d = param(TraitKind.VANISH_WHEN_APPROACHED, "distance") ?: 8.0
            lines += "execute if score #chase $tmp matches 0 if entity @p[distance=..${d.roundToInt()},gamemode=!spectator] run function $ns:$base/vanish"
            ok("Vanishes when approached within ${d.roundToInt()} blocks", "functions: sound, smoke, rig removed, mob removed below the world",
                "removal is a teleport below the world then /kill, not Java's discard()", FeatureStatus.IMPLEMENTED, TraitKind.VANISH_WHEN_APPROACHED)
        }
        if (has(TraitKind.VANISH_WHEN_LOOKED_AT)) {
            lines += "execute if score #looked $tmp matches 1 run function $ns:$base/vanish"
            ok("Vanishes when looked at", "functions: view-direction probes then the vanish sequence", "the view test has no wall check", k = TraitKind.VANISH_WHEN_LOOKED_AT)
        }
        if (has(TraitKind.TELEPORT_NEAR_PLAYER)) {
            val d = param(TraitKind.TELEPORT_NEAR_PLAYER, "distance") ?: 12.0
            lines += "execute if score #slow $tmp matches 0 if predicate $ns:chance/particles unless entity @p[distance=..${d.roundToInt()}] at @p[gamemode=!spectator] rotated as @p run tp @s ^ ^ ^-${d.roundToInt()}"
            ok("Teleports near the player", "functions: occasionally appears ${d.roundToInt()} blocks behind the nearest player", "no ground search: it can land in the air or a wall", k = TraitKind.TELEPORT_NEAR_PLAYER)
        }

        // Effects, particles, sounds.
        for (t in traits[TraitKind.APPLY_EFFECT_TO_PLAYER].orEmpty()) {
            val effect = t.params["effect"]?.takeIf { it.startsWith("minecraft:") } ?: continue
            val secs = ((t.params["duration_ticks"]?.toDoubleOrNull() ?: 100.0) / 20).roundToInt().coerceAtLeast(1)
            val gated = night && traits[TraitKind.NIGHT_ONLY]!!.any { n -> n.evidence.any { ev -> t.evidence.any { it.substringBefore(':') == ev.substringBefore(':') } } }
            val prefix = if (gated) "execute if score #night $tmp matches 1 run " else ""
            lines += "${prefix}effect give @a[distance=..16,gamemode=!spectator] $effect $secs 0 true"
            ok("Gives nearby players ${effect.removePrefix("minecraft:")}${if (gated) " at night" else ""}", "functions: effect give within 16 blocks",
                "the radius is 16 blocks; the Java code's own range was not recoverable as a constant", k = TraitKind.APPLY_EFFECT_TO_PLAYER)
        }
        traits[TraitKind.FOG_OR_DARKNESS]?.let {
            lines += "effect give @a[distance=..24,gamemode=!spectator] minecraft:darkness 3 0 true"
            ok("Fog around the player", "functions: darkness effect nearby", "the original changes the renderer's fog; Horizon Android has no fog API for mods", k = TraitKind.FOG_OR_DARKNESS)
        }
        val particles = traits[TraitKind.SPAWN_PARTICLES].orEmpty().mapNotNull { it.params["particle"]?.takeIf { p -> p.startsWith("minecraft:") } }.distinct()
        for (pt in particles) lines += "execute if predicate $ns:chance/particles run particle $pt ~ ~1.5 ~ 0.3 0.6 0.3 0.01 2"
        if (particles.isNotEmpty()) ok("Particles: ${particles.joinToString { it.removePrefix("minecraft:") }}", "functions: particle around the mob", "spawn rate approximated", k = TraitKind.SPAWN_PARTICLES)
        soundId(e.sounds.ambient)?.let {
            lines += "execute if predicate $ns:chance/ambient run playsound $it hostile @a[distance=..32] ~ ~ ~ 1 1"
            ok("Ambient sound", "functions: playsound $it about every 4 seconds", "vanilla's ambient timer is replaced by a random chance", FeatureStatus.IMPLEMENTED)
        }
        soundId(e.sounds.hurt)?.let {
            lines += "execute if entity @s[nbt={HurtTime:10s}] run playsound $it hostile @a[distance=..32] ~ ~ ~ 1 1"
            ok("Hurt sound", "functions: playsound when hurt", status = FeatureStatus.IMPLEMENTED)
        }
        if (e.sounds.death != null) ok("Death sound", "", "a dead mob is no longer selectable by functions; the template is silenced", FeatureStatus.UNSUPPORTED)

        // Attacks: a nearby player was just hurt while it chases.
        val attackSound = traits[TraitKind.PLAY_SOUND].orEmpty().firstOrNull { it.params["context"]?.let { c -> c.contains("HurtTarget") || c.contains("attack") || c == "m_7327_" || c == "method_6121" } == true }
            ?.params?.get("sound")?.let { soundId(it) }
        lines += "scoreboard players set #hit $tmp 0"
        lines += "execute if score #chase $tmp matches 1 as @a[distance=..3.5,nbt={HurtTime:10s}] run scoreboard players set #hit $tmp 1"
        lines += "execute if score #hit $tmp matches 1 run scoreboard players set @s $obj.atk 16"
        attackSound?.let {
            lines += "execute if score #hit $tmp matches 1 run playsound $it hostile @a[distance=..32] ~ ~ ~ 2 1"
            ok("Attack sound", "functions: playsound $it on a hit", status = FeatureStatus.IMPLEMENTED, k = TraitKind.PLAY_SOUND)
        }
        traits[TraitKind.JUMPSCARE_OVERLAY]?.firstOrNull()?.let { t ->
            val texture = t.params["texture"] ?: ""
            val file = texture.substringAfter("textures/").removeSuffix(".png")
            if (file.isNotEmpty()) {
                out.putJson("assets/$ns/font/jumpscare.json", JsonTree.of("providers" to listOf(JsonTree.of(
                    "type" to "bitmap", "file" to "$ns:$file.png", "height" to 120, "ascent" to 60, "chars" to listOf("\uE000")))))
                lines += "execute if score #hit $tmp matches 1 run title @a[distance=..4] times 0 12 6"
                lines += "execute if score #hit $tmp matches 1 run title @a[distance=..4] title {\"text\":\"\\uE000\",\"font\":\"$ns:jumpscare\"}"
                ok("Jumpscare image", "functions: the image as a title glyph (bitmap font) when it hits a player",
                    "the original draws a GUI overlay; a title glyph is smaller and fades; font support on Horizon Android not verified", k = TraitKind.JUMPSCARE_OVERLAY)
            }
        }
        if (has(TraitKind.PERSISTENT)) ok("Never despawns", "PersistenceRequired on spawn", status = FeatureStatus.IMPLEMENTED, k = TraitKind.PERSISTENT)
        for (k in listOf(TraitKind.BREAK_BLOCKS, TraitKind.TOGGLE_INVISIBILITY, TraitKind.CUSTOM_PACKET, TraitKind.CUSTOM_RENDERER)) {
            if (has(k)) ok(k.name.lowercase().replace('_', ' ').replaceFirstChar(Char::uppercase), "", "needs Java code with no data or command equivalent", FeatureStatus.UNSUPPORTED, k)
        }
        if (has(TraitKind.LINE_OF_SIGHT_CHECK)) ok("Line-of-sight checks", "", "commands cannot test line of sight; behaviours that used it run without it", FeatureStatus.PARTIAL, TraitKind.LINE_OF_SIGHT_CHECK)
        if (has(TraitKind.CUSTOM_SPAWN_RULE)) ok("Custom spawn rule", "biome modifier spawns with the template's rules", "Java spawn predicates are code", FeatureStatus.PARTIAL, TraitKind.CUSTOM_SPAWN_RULE)
        if (has(TraitKind.CUSTOM_MELEE)) ok("Custom melee hit", "template melee", "the overridden doHurtTarget's extra effects are only reproduced where listed above", FeatureStatus.PARTIAL, TraitKind.CUSTOM_MELEE)
        return lines
    }
